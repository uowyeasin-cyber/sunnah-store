// Built-in translations merged with the admin's own (admin wins).
export function dictFor(lang: Lang, overrides: Partial<Record<Lang, Dict>> = {}): Dict {
  const base: Dict = lang === 'en' ? {} : Object.fromEntries(ROWS.map(r => [r[0], r[COL[lang]]]));
  return { ...base, ...(overrides[lang] || {}) };
}

export function makeT(dict: Dict) {
  return (s: string, vars?: Record<string, string | number>) => {
    let out = (s && dict[s]) || s;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
    return out;
  };
}
export type T = ReturnType<typeof makeT>;
